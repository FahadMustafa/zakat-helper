// Bundle the engine + CLI into one dependency-free file for the agent skill.
import { build } from 'esbuild';

export const BANNER = '// Generated by scripts/build-skill.mjs from cli/zakat.ts. Do not edit.';

export async function bundle(outfile) {
  await build({
    entryPoints: ['cli/zakat.ts'],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    outfile,
    banner: { js: BANNER },
    legalComments: 'none',
    minify: true,
    logLevel: 'warning',
  });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await bundle('skills/zakat/scripts/zakat.mjs');
}
